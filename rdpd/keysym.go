package main

// X11 keysym -> PS/2 Set 1 扫描码映射（美式键盘布局）。
// RDP 侧按扫描码输入，扩展键（方向键/Delete/Home/Win 等）带 KBDFLAGS_EXTENDED。

type keyDef struct {
	sc  int  // PS/2 Set 1 make code
	ext bool // 扩展键（0xE0 前缀）
}

var keysymMap = buildKeysymMap()

func buildKeysymMap() map[int]keyDef {
	m := make(map[int]keyDef, 200)

	add := func(ks, sc int) { m[ks] = keyDef{sc: sc} }
	addExt := func(ks, sc int) { m[ks] = keyDef{sc: sc, ext: true} }

	// 功能键
	for i, sc := range []int{0x3B, 0x3C, 0x3D, 0x3E, 0x3F, 0x40, 0x41, 0x42, 0x43, 0x44} {
		add(0xFFBE+i, sc) // F1-F10
	}
	add(0xFFC8, 0x57) // F11
	add(0xFFC9, 0x58) // F12

	// 控制键
	add(0xFF1B, 0x01) // Escape
	add(0xFF09, 0x0F) // Tab
	add(0xFE20, 0x0F) // ISO Left Tab
	add(0xFF08, 0x0E) // Backspace
	add(0xFF0D, 0x1C) // Return
	m[0xFF8D] = keyDef{sc: 0x1C, ext: true} // KP_Enter
	add(0xFFE5, 0x3A)                       // Caps Lock
	add(0xFF7F, 0x45)                       // Num Lock
	add(0xFF14, 0x46)                       // Scroll Lock

	// 修饰键
	add(0xFFE1, 0x2A) // Shift L
	add(0xFFE2, 0x36) // Shift R
	add(0xFFE3, 0x1D) // Control L
	addExt(0xFFE4, 0x1D) // Control R
	add(0xFFE9, 0x38) // Alt L
	addExt(0xFFEA, 0x38) // Alt R
	add(0xFFE7, 0x38) // Meta L -> Alt L
	addExt(0xFFE8, 0x38) // Meta R -> Alt R
	addExt(0xFFEB, 0x5B) // Super L (Win)
	addExt(0xFFEC, 0x5C) // Super R
	addExt(0xFFED, 0x5B) // Hyper L
	addExt(0xFFEE, 0x5C) // Hyper R
	addExt(0xFF67, 0x5D) // Menu

	// 编辑/导航键（扩展）
	addExt(0xFF63, 0x52) // Insert
	addExt(0xFFFF, 0x53) // Delete
	addExt(0xFF50, 0x47) // Home
	addExt(0xFF57, 0x4F) // End
	addExt(0xFF55, 0x49) // Prior (Page Up)
	addExt(0xFF56, 0x51) // Next (Page Down)
	addExt(0xFF51, 0x4B) // Left
	addExt(0xFF52, 0x48) // Up
	addExt(0xFF53, 0x4D) // Right
	addExt(0xFF54, 0x50) // Down
	addExt(0xFF61, 0x37) // Print Screen（近似）

	// 小键盘
	add(0xFFAF, 0x35)
	m[0xFFAF] = keyDef{sc: 0x35, ext: true} // KP_Divide
	add(0xFFAA, 0x37)                       // KP_Multiply
	add(0xFFAD, 0x4A)                       // KP_Subtract
	add(0xFFAB, 0x4E)                       // KP_Add
	add(0xFFAE, 0x53)                       // KP_Decimal
	kpDigits := []int{0x52, 0x4F, 0x50, 0x51, 0x4B, 0x4C, 0x4D, 0x47, 0x48, 0x49}
	for i, sc := range kpDigits {
		add(0xFFB0+i, sc) // KP_0 - KP_9
	}
	// KP_ Home/Up/Prior/Left/Begin/Right/End/Down/Next/Insert/Delete（NumLock 关态等价编辑键）
	add(0xFF95, 0x47)
	add(0xFF97, 0x48)
	add(0xFF99, 0x49)
	add(0xFF96, 0x4B)
	add(0xFF9D, 0x4C)
	add(0xFF98, 0x4D)
	add(0xFF9C, 0x4F)
	add(0xFF9A, 0x50)
	add(0xFF9B, 0x51)
	add(0xFF9E, 0x52) // KP Insert
	add(0xFF9F, 0x53) // KP Delete

	// 可打印 ASCII（Latin-1 区与 X11 一致）
	printable := map[rune]int{
		' ': 0x39, '!': 0x02, '"': 0x28, '#': 0x04, '$': 0x05, '%': 0x06,
		'&': 0x08, '\'': 0x28, '(': 0x0A, ')': 0x0B, '*': 0x09, '+': 0x0D,
		',': 0x33, '-': 0x0C, '.': 0x34, '/': 0x35,
		'0': 0x0B, '1': 0x02, '2': 0x03, '3': 0x04, '4': 0x05,
		'5': 0x06, '6': 0x07, '7': 0x08, '8': 0x09, '9': 0x0A,
		':': 0x27, ';': 0x27, '<': 0x33, '=': 0x0D, '>': 0x34, '?': 0x35, '@': 0x03,
		'[': 0x1A, '\\': 0x2B, ']': 0x1B, '^': 0x07, '_': 0x0C, '`': 0x29,
		'{': 0x1A, '|': 0x2B, '}': 0x1B, '~': 0x29,
	}
	for r, sc := range printable {
		m[int(r)] = keyDef{sc: sc}
	}
	// A-Z / a-z
	letters := map[rune]int{
		'A': 0x1E, 'B': 0x30, 'C': 0x2E, 'D': 0x20, 'E': 0x12, 'F': 0x21,
		'G': 0x22, 'H': 0x23, 'I': 0x17, 'J': 0x24, 'K': 0x25, 'L': 0x26,
		'M': 0x32, 'N': 0x31, 'O': 0x18, 'P': 0x19, 'Q': 0x10, 'R': 0x13,
		'S': 0x1F, 'T': 0x14, 'U': 0x16, 'V': 0x2F, 'W': 0x11, 'X': 0x2D,
		'Y': 0x15, 'Z': 0x2C,
	}
	for r, sc := range letters {
		m[int(r)] = keyDef{sc: sc}
		m[int(r) + 32] = keyDef{sc: sc} // 小写
	}
	return m
}
