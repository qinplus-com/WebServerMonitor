package brand

// 品牌信息以 XOR 方式加密存储，运行时解密；
// 避免公司名称、官方网址、版权信息以明文形式出现在二进制文件中被检索或修改。
// 版权信息另附 SHA-256 完整性签名：密文被篡改时校验失败、拒绝输出，
// 且系统中不存在任何可修改版权的接口，保证登录页/关于页版权不可变更。

import (
	"crypto/sha256"
	"log"
)

var brandKey = []byte{0x5A, 0x3C, 0x7F, 0x91, 0x24, 0x68, 0xB3, 0xD7, 0x1E, 0x45, 0x8C, 0xA9, 0xF2, 0x06, 0x31, 0x77}

var encCompany = []byte{0xBF, 0xBA, 0xFA, 0x79, 0xB6, 0xF1, 0x56, 0x58, 0xBA, 0xA0, 0x07, 0x0D, 0x17, 0x8C, 0x91, 0x9F, 0xE7, 0x93, 0x9B, 0x2A, 0x92, 0x8E, 0x2F, 0x5E, 0xF7, 0xDC, 0x1C, 0x4C, 0x77, 0xAA, 0xD4, 0xF8, 0xE2}

var encWebsite = []byte{0x32, 0x48, 0x0B, 0xE1, 0x57, 0x52, 0x9C, 0xF8, 0x6F, 0x2C, 0xE2, 0xD9, 0x9E, 0x73, 0x42, 0x59, 0x39, 0x53, 0x12}

// 版权全文密文：「© 2026 内蒙古勤加软件有限公司 版权所有」
var encCopyright = []byte{0x98, 0x95, 0x5F, 0xA3, 0x14, 0x5A, 0x85, 0xF7, 0xFB, 0xC3, 0x09, 0x41, 0x60, 0x9F, 0xD4, 0xF8, 0xFE, 0xD9, 0xF4, 0x35, 0xC1, 0xE2, 0x13, 0x3F, 0xA3, 0xEA, 0x68, 0x12, 0x44, 0xE0, 0xAD, 0xFE, 0xB3, 0xA5, 0xEF, 0x74, 0xA1, 0xC4, 0x56, 0x58, 0xA6, 0x65, 0x6B, 0x20, 0x7A, 0xE0, 0xAC, 0xF4, 0xBC, 0xB5, 0xFF, 0x77, 0xB8, 0xE1}

// 版权完整性签名：SHA-256(明文 + salt) 前 8 字节
var copyrightSig = []byte{0x22, 0xA4, 0x21, 0x3A, 0xDC, 0xED, 0xAA, 0xC1}
var copyrightSalt = []byte("qj-brand-sig-v1")

func decode(enc []byte) string {
	b := make([]byte, len(enc))
	for i := range enc {
		b[i] = enc[i] ^ brandKey[i%len(brandKey)]
	}
	return string(b)
}

// Company 返回公司名称
func Company() string { return decode(encCompany) }

// Website 返回官方网站网址
func Website() string { return decode(encWebsite) }

// Copyright 返回版权声明：先解密，再以 SHA-256 签名校验完整性。
// 密文/签名被篡改导致校验失败时返回空串并记录日志（拒绝输出被篡改的内容）。
func Copyright() string {
	raw := []byte(decode(encCopyright))
	sum := sha256.Sum256(append(raw, copyrightSalt...))
	for i := range copyrightSig {
		if sum[i] != copyrightSig[i] {
			log.Printf("brand: copyright integrity check failed, content has been tampered")
			return ""
		}
	}
	return string(raw)
}
