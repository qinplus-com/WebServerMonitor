# 将公钥和 AES 密钥编码为 Go 常量文件
# 用法: .\embed-keys.ps1

$ErrorActionPreference = 'Stop'

$pubKeyFile = "$PSScriptRoot\keys\public.pem"
$encKeyFile = "$PSScriptRoot\keys\encrypt.key"

if (-not (Test-Path $pubKeyFile)) {
    Write-Error "公钥文件不存在: $pubKeyFile"
    exit 1
}
if (-not (Test-Path $encKeyFile)) {
    Write-Error "加密密钥文件不存在: $encKeyFile"
    exit 1
}

# 公钥 → Base64（去掉换行，保留完整 DER）
$pubKeyPem = Get-Content $pubKeyFile -Raw
$pubKeyDer = [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($pubKeyPem))

# AES 密钥 → Base64
$encKeyBytes = [IO.File]::ReadAllBytes($encKeyFile)
$encKeyBase64 = [Convert]::ToBase64String($encKeyBytes)

$goCode = @"// Code generated by embed-keys.ps1. DO NOT EDIT.
package license

const _embeddedPublicKeyB64 = "$pubKeyDer"
const _embeddedLicenseKeyB64 = "$encKeyBase64"
"@

$outFile = "$PSScriptRoot\..\license\keys_generated.go"
Set-Content -Path $outFile -Value $goCode -Encoding UTF8

Write-Host "密钥常量文件已生成: $outFile" -ForegroundColor Green
Write-Host "  公钥 DER Base64: $($pubKeyDer.Length) 字符"
Write-Host "  AES 密钥 Base64: $encKeyBase64"
